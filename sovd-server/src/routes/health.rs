//! `GET /sovd/v1/health` — liveness probe. Preserved verbatim from the
//! Phase-0 hello-world server.

use axum::Json;
use serde_json::{Value, json};

/// Return an `{ "status": "ok", "version": "<crate version>" }` envelope.
pub async fn health() -> Json<Value> {
    Json(json!({
        "status": "ok",
        "version": env!("CARGO_PKG_VERSION"),
    }))
}
